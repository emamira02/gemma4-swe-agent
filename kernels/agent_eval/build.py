"""Generate the Kaggle GPU kernel that runs the agent bundle end to end with the official harness on a dev panel.

    python kernels/agent_eval/build.py --tag S1 [--n 24] [--seed 0] [--repos Textualize/rich]

The kernel mirrors the scorer: 4xL4, vLLM with the scorer's settings (TP=4, gpu_memory_utilization 0.80,
max_model_len 32768, gemma4 tool/reasoning parsers), sequential tasks, the bundle's own eval_config budgets.
Per task it also verifies the reference patch (agent phase replaced by the gold patch), so the resolve rate can
be reported over tasks that are solvable in this environment (fastapi tasks are not: pydantic cannot import).
Outputs under /kaggle/working/agent_eval/: per_task.jsonl, summary.json and the harness results dir
(patches/, logs/, traces/, test_outputs/).
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT))

TEMPLATE = r'''# Auto-generated by kernels/agent_eval/build.py -- bundle {tag} (sha256 {sha}). Do not edit by hand.
import asyncio, base64, glob, hashlib, io, json, os, shutil, subprocess, sys, time, traceback, zipfile
from pathlib import Path

T0 = time.time()
os.environ.update(LITELLM_LOCAL_MODEL_COST_MAP="True", TRANSFORMERS_NO_TF="1", VLLM_WORKER_MULTIPROC_METHOD="spawn",
                  VLLM_MEMORY_PROFILER_ESTIMATE_CUDAGRAPHS="1", VLLM_ENGINE_READY_TIMEOUT_S="1200", VLLM_NO_USAGE_STATS="1",
                  OTEL_SDK_DISABLED="true", PYTORCH_CUDA_ALLOC_CONF="expandable_segments:True")
WHEELHOUSE = Path("/kaggle/input/datasets/metric/gemma-4-developer-agent-wheelhouse")
for pat in ("/usr/local/lib/python*/dist-packages/*cutlass*.pth", "/usr/local/lib/python*/site-packages/*cutlass*.pth"):
    for pth in glob.glob(pat):
        try:
            os.unlink(pth)
        except OSError:
            pass
tmp = Path("/tmp/wheelhouse"); tmp.mkdir(parents=True, exist_ok=True)
for w in WHEELHOUSE.glob("*.whl"):
    if "cutlass" in w.name.lower():
        continue
    name = w.name.replace("cu128", "+cu128") if ("cu128" in w.name and "+" not in w.name) else w.name
    if not (tmp / name).exists():
        os.symlink(w, tmp / name)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "--no-deps", "--force-reinstall",
                *sorted(str(w) for w in tmp.glob("*.whl"))], check=True)
import importlib; importlib.invalidate_caches()

DATA = Path("/kaggle/input/competitions/gemma-4-developer-agent")
WORK = Path("/kaggle/working"); OUT = WORK / "agent_eval"; OUT.mkdir(parents=True, exist_ok=True)
AGENT = WORK / "agent"
ZIP = base64.b64decode("{zip_b64}")
assert hashlib.sha256(ZIP).hexdigest() == "{sha}"
shutil.rmtree(AGENT, ignore_errors=True)
zipfile.ZipFile(io.BytesIO(ZIP)).extractall(AGENT)
PANEL = {panel}

import litellm, torch, yaml
from adk_submission import VllmConfig, VllmServer, discover_adapters
from swegemma.config import ALLOWED_ADAPTER_EXTENSIONS, EvalConfig, build_submission_limits
from swegemma.evaluate import Evaluator
from swegemma.models import load_tasks
from google.adk.agents.context_cache_config import ContextCacheConfig
from google.adk.apps._configs import EventsCompactionConfig
litellm.drop_params = True

MODEL = "gemma-4-31b-it-qat-w4a16-ct"
adapters = discover_adapters(str(AGENT), adapter_extensions=ALLOWED_ADAPTER_EXTENSIONS)
n_gpu = torch.cuda.device_count()
server = VllmServer(VllmConfig(model="/kaggle/input/models/google/gemma-4/other/gemma-4-31b-it-qat-w4a16-ct/2",
                               port=8000, host="127.0.0.1", tool_call_parser="gemma4", reasoning_parser="gemma4",
                               max_model_len=32768, dtype="bfloat16", gpu_memory_utilization=0.80,
                               enable_auto_tool_choice=True, enable_lora=True, max_loras=8, max_lora_rank=128,
                               tensor_parallel_size=4 if n_gpu >= 4 else (2 if n_gpu >= 2 else 1),
                               startup_timeout=60 * 20), adapter_manifest=adapters)
server.start()
models = server.create_model_registry(aliases=[MODEL], model_prefix="openai/", api_key="EMPTY")
T_SERVER = time.time() - T0
print(f"vLLM ready after {{T_SERVER:.0f}}s on {{n_gpu}} GPUs", flush=True)

ev = (yaml.safe_load((AGENT / "eval_config.yaml").read_text()) or {{}}).get("evaluation", {{}})
limits, gen = build_submission_limits()
def make_cfg(results_dir):
    return EvalConfig(tasks_path=DATA / "tasks.jsonl", snapshots_dir=DATA / "snapshots", results_dir=results_dir,
                      submission_dir=AGENT, models=models, sandbox="subprocess",
                      timeout_seconds=int(ev.get("timeout_seconds", 300)), max_time_minutes=float(ev.get("max_time_minutes", 60)),
                      max_tool_calls=int(ev.get("max_tool_calls", 100)), max_turns=ev.get("max_turns"),
                      limits=limits, generation_constraints=gen, adapter_manifest=adapters,
                      context_cache_config=ContextCacheConfig(min_tokens=2048, ttl_seconds=1800, cache_intervals=10),
                      events_compaction_config=EventsCompactionConfig(compaction_interval=5, overlap_size=2,
                                                                      token_threshold=14336, event_retention_size=5),
                      graph_dir=str(DATA / "graphs"), embeddings_dir=str(DATA / "embeddings"),
                      wheels_dir=DATA / "wheels", verbose=False)

tasks = {{t.instance_id: t for t in load_tasks(DATA / "tasks.jsonl")}}
panel = [tasks[i] for i in PANEL if i in tasks]
agent_ev, gold_ev = Evaluator(make_cfg(OUT / "results")), Evaluator(make_cfg(OUT / "gold"))
async def _gold_phase1(task, *a, **k):
    from adk_eval_core import SessionTrace
    return task.patch, None, SessionTrace()
gold_ev._run_agent_sandbox = _gold_phase1

rows = []
with open(OUT / "per_task.jsonl", "w") as fh:
    for i, t in enumerate(panel, 1):
        row = {{"id": t.instance_id, "repo": t.repo}}
        for name, evaluator in (("agent", agent_ev), ("gold", gold_ev)):
            t1 = time.time()
            try:
                r = asyncio.run(evaluator.evaluate_task(task=t, task_index=i, total_tasks=len(panel)))
                row[name] = {{"resolved": bool(r.resolved), "exit": r.test_exit_code, "patch_chars": len(r.agent_patch or ""),
                             "tool_calls": getattr(r, "tool_calls", None), "error": (r.error or "")[:300],
                             "duration_s": round(time.time() - t1, 1),
                             "agent_s": getattr(r, "agent_duration_seconds", None)}}
            except Exception as e:
                row[name] = {{"resolved": False, "error": f"{{type(e).__name__}}: {{e}}"[:300], "duration_s": round(time.time() - t1, 1)}}
                traceback.print_exc()
        rows.append(row); fh.write(json.dumps(row) + "\n"); fh.flush()
        print(f"[{{i}}/{{len(panel)}}] {{t.instance_id}} agent={{row['agent'].get('resolved')}} gold={{row['gold'].get('resolved')}} "
              f"t={{row['agent'].get('duration_s')}}s", flush=True)

solv = [r for r in rows if r["gold"].get("resolved")]
summary = {{"tag": "{tag}", "sha256": "{sha}", "n": len(rows), "resolved": sum(r["agent"].get("resolved", False) for r in rows),
           "gold_solvable": len(solv), "resolved_on_solvable": sum(r["agent"].get("resolved", False) for r in solv),
           "agent_phase_s_mean": round(sum(r["agent"].get("duration_s", 0) for r in rows) / max(1, len(rows)), 1),
           "server_start_s": round(T_SERVER), "wall_s": round(time.time() - T0), "eval_config": ev}}
(OUT / "summary.json").write_text(json.dumps(summary, indent=1))
print(json.dumps(summary, indent=1))
server.stop() if hasattr(server, "stop") else None
'''


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", required=True)
    ap.add_argument("--zip", type=Path, default=None,
                    help="default: rebuild candidates/<tag>/bundle and require the sha in its MANIFEST")
    ap.add_argument("--n", type=int, default=24)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--repos", nargs="+", default=["Textualize/rich"])
    ap.add_argument("--mix", nargs="+", default=None, metavar="REPO=N",
                    help="mixed panel: N tasks per repository, each sampled with its own seed; overrides --n/--repos")
    ap.add_argument("--pools", type=Path, default=None,
                    help="JSON {repo: [instance ids]} restricting --mix sampling (e.g. results/gold_check/pools.json)")
    ap.add_argument("--kernel-id", default="emanuelemiranda/g4-agent-eval")
    ap.add_argument("--force", action="store_true", help="replace panel.json before the previous panel was downloaded")
    a = ap.parse_args()
    prev = json.loads((HERE / "panel.json").read_text(encoding="utf-8")) if (HERE / "panel.json").exists() else None
    if (prev and prev["tag"] != a.tag and not a.force
            and not (ROOT / "results" / f"kaggle_eval_{prev['tag']}" / "agent_eval" / "summary.json").exists()):
        # tools/status.py names the running kernel's output after panel.json: replacing it now would file the
        # previous tag's results under this tag
        sys.exit(f"panel {prev['tag']} has not been downloaded yet (python tools/status.py); refusing to replace it")
    if a.zip is None:  # the panel must run exactly the frozen bytes that a submission of this tag would send
        from tools import build_submission as bs
        man = bs.CANDIDATES / a.tag / "MANIFEST.json"
        if not man.exists():
            sys.exit(f"no frozen candidate {a.tag}: python tools/build_submission.py --tag {a.tag} first")
        import tempfile
        with tempfile.TemporaryDirectory() as td:
            staged = bs.stage(man.parent / "bundle", Path(td) / "s")
            bs.validate(staged)
            data = bs.build_zip(staged)
        if hashlib.sha256(data).hexdigest() != json.loads(man.read_text(encoding="utf-8"))["zip_sha256"]:
            sys.exit(f"candidates/{a.tag} does not rebuild to its recorded sha")
    else:
        data = a.zip.read_bytes()
    sha = hashlib.sha256(data).hexdigest()
    tasks = [json.loads(l) for l in (ROOT / "data" / "tasks.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
    if a.mix:
        pools = json.loads(a.pools.read_text(encoding="utf-8")) if a.pools else {}
        known = {t["instance_id"] for t in tasks}
        panel = []
        for spec in a.mix:
            repo, _, n = spec.rpartition("=")
            pool = sorted(pools[repo]) if repo in pools else sorted(t["instance_id"] for t in tasks if t["repo"] == repo)
            if not repo or not n.isdigit() or not pool or not set(pool) <= known or int(n) > len(pool):
                sys.exit(f"bad --mix entry {spec!r}: need REPO=N with N <= {len(pool)} known tasks")
            panel += random.Random(f"{a.seed}:{repo}").sample(pool, int(n))
        panel = sorted(panel)
        a.repos = [s.rpartition("=")[0] for s in a.mix]
    else:
        pool = sorted(t["instance_id"] for t in tasks if t["repo"] in a.repos)
        panel = sorted(random.Random(a.seed).sample(pool, min(a.n, len(pool))))
    src = TEMPLATE.format(tag=a.tag, sha=sha, zip_b64=base64.b64encode(data).decode(), panel=json.dumps(panel))
    compile(src, "run_agent_eval.py", "exec")
    (HERE / "run_agent_eval.py").write_text(src, encoding="utf-8")
    meta = {"id": a.kernel_id, "title": "g4-agent-eval", "code_file": "run_agent_eval.py", "language": "python",
            "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_tpu": False, "enable_internet": False,
            "dataset_sources": ["metric/gemma-4-developer-agent-wheelhouse"],
            "competition_sources": ["gemma-4-developer-agent"], "kernel_sources": [],
            "model_sources": ["google/gemma-4/Other/gemma-4-31b-it-qat-w4a16-ct/2"],
            "docker_image": "gcr.io/kaggle-private-byod/python@sha256:37c64f7dd9c54116ecd1bcc88817c5469b88387388fade02bfa8bf3fc647d461",
            "machine_shape": "NvidiaL4"}
    (HERE / "kernel-metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    (HERE / "panel.json").write_text(json.dumps({"tag": a.tag, "sha256": sha, "seed": a.seed, "repos": a.repos,
                                                 "mix": a.mix, "pools": str(a.pools) if a.pools else None,
                                                 "panel": panel}, indent=1), encoding="utf-8")
    print(f"kernel for {a.tag} ({sha[:12]}): {len(panel)} tasks -> {HERE / 'run_agent_eval.py'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
