def main() -> None:
    scripts = SKILL / "scripts"
    files = {n: base64.b64encode((scripts / n).read_bytes()).decode() for n in ("localize.py", "finalize.py", "edit.py")}
    src = (CHECK.replace("__FILES__", json.dumps(files))
           .replace("__SKILL__", base64.b64encode((SKILL / "SKILL.md").read_bytes()).decode()))
    compile(src, "check.py", "exec")
    (HERE / "check.py").write_text(src, encoding="utf-8", newline="\n")
    meta = {"id": "emanuelemiranda/g4-editor-linux-check", "title": "g4-editor-linux-check", "code_file": "check.py",
            "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": False,
            "enable_tpu": False, "enable_internet": False, "dataset_sources": ["metric/gemma-4-developer-agent-wheelhouse"],
            "competition_sources": ["gemma-4-developer-agent"], "kernel_sources": [], "model_sources": [],
            # the dev-panel kernel's image (Python 3.12): the competition wheelhouse is built for cp312
            "docker_image": json.loads((HERE.parent / "agent_eval" / "kernel-metadata.json").read_text(encoding="utf-8"))
            ["docker_image"]}
    (HERE / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {HERE / 'check.py'} ({sum(len(v) for v in files.values())} b64 bytes of scripts)")


if __name__ == "__main__":
    main()
