        subprocess.run(["git", "-C", sws, "checkout", "-q", "--", "pkg/markup.py"])
        code, out = run("python3 /workspace/.git/swe/edit.py pkg/markup.py <<EOF\n" + BLOCK + "EOF")
        case("B unquoted heredoc recovered", code == 0 and NEW.encode() in read("pkg/markup.py", sws), out)
        subprocess.run(["git", "-C", sws, "checkout", "-q", "--", "pkg/markup.py"])
        lit = '    return "/tmp/cache:/workspace/x:/usr/local/bin/y"'
        code, out = run("python3 /workspace/.git/swe/edit.py pkg/markup.py <<'EOF'\n<<<<<<< SEARCH\n    return 1\n=======\n"
                        + lit + "\n>>>>>>> REPLACE\nEOF")
        case("B code naming /tmp, /workspace, /usr/local/bin reaches the file as written",
             code == 0 and (lit + "\n").encode() in read("pkg/markup.py", sws), out + "\nFILE:\n" + read("pkg/markup.py", sws).decode())
        subprocess.run(["git", "-C", sws, "checkout", "-q", "--", "pkg/markup.py"])
        code, out = run("python3 /workspace/.git/swe/edit.py pkg/markup.py <<'EOF'\n<<<<<<< SEARCH\n    nothing here\n"
                        "=======\nx\n>>>>>>> REPLACE\nEOF")
