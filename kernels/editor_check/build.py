"""Generate a CPU-only Kaggle kernel that checks the editor on Linux through the harness's exact exec chain.

    python kernels/editor_check/build.py && python -m kaggle kernels push -p kernels/editor_check

The grader runs run_command as  /bin/bash -c "timeout -k 5s N /bin/bash -c <shlex-quoted command>"  inside the task
container (swegemma sandbox/docker.py), and run_skill_script materializes the skill scripts in a temporary directory
(google.adk skill_toolset). check.py reproduces both on a throwaway git repo and prints one PASS/FAIL line per case
plus a JSON summary: quoted and unquoted heredocs (/proc recovery), a call cut short before its terminator, line
ranges, new files, refusals, atomicity and exit codes. No GPU, no internet, no competition data.
"""
from __future__ import annotations

import base64
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCRIPTS = HERE.parents[1] / "agent" / "skills" / "swe" / "scripts"

CHECK = r'''# Auto-generated by kernels/editor_check/build.py. Do not edit by hand.
import base64, json, os, shlex, shutil, subprocess, sys, tempfile

FILES = __FILES__
WS = tempfile.mkdtemp(prefix="ws_")
RESULTS = []


def sh(cmd, timeout=100):
    """The grader's run_command: docker exec bash -c 'timeout -k 5s N /bin/bash -c <quoted>' (cwd = workspace)."""
    outer = f"timeout -k 5s {timeout} /bin/bash -c {shlex.quote(cmd)}"
    r = subprocess.run(["/bin/bash", "-c", outer], cwd=WS, capture_output=True, timeout=timeout + 30)
    return r.returncode, r.stdout.decode("utf-8", "replace"), r.stderr.decode("utf-8", "replace")


def case(name, ok, detail=""):
    RESULTS.append({"case": name, "ok": bool(ok), "detail": detail[-600:]})
    print(("PASS " if ok else "FAIL ") + name + ("" if ok else "\n" + detail[-1500:]), flush=True)


def read(rel):
    with open(os.path.join(WS, rel), "rb") as fh:
        return fh.read()


def git(*a):
    return subprocess.run(["git", "-C", WS, *a], capture_output=True, text=True).stdout


os.makedirs(os.path.join(WS, "pkg"))
SRC = ('import re\n\n\ndef escape(markup):\n    """Escape [ and \\\\ in markup."""\n'
       '    markup = re.sub(r"(\\\\*)(\\[[a-z#/@][^[]*?])", r"\\1\\1\\\\\\2", markup)\n    return markup\n\n\n'
       'def other():\n    return 1\n')
with open(os.path.join(WS, "pkg", "markup.py"), "w") as fh:
    fh.write(SRC)
with open(os.path.join(WS, "pkg", "crlf.py"), "wb") as fh:
    fh.write(b"A = 1\r\nB = 2\r\n")
os.makedirs(os.path.join(WS, "tests"))
with open(os.path.join(WS, "tests", "test_markup.py"), "w") as fh:
    fh.write("def test_x():\n    pass\n")
for c in (["init", "-q"], ["-c", "user.email=a@b", "-c", "user.name=t", "add", "-A"],
          ["-c", "user.email=a@b", "-c", "user.name=t", "commit", "-qm", "base"]):
    subprocess.run(["git", "-C", WS, *c], check=True)

# 1. install: run localize the way run_skill_script does (scripts materialized in a temp dir, cwd = that dir)
td = tempfile.mkdtemp(prefix="skill_")
os.makedirs(os.path.join(td, "scripts"))
for name, b64 in FILES.items():
    with open(os.path.join(td, "scripts", name), "wb") as fh:
        fh.write(base64.b64decode(b64))
shutil.rmtree("/tmp/swe", ignore_errors=True)
r = subprocess.run([sys.executable, "-c", "import runpy, sys; sys.argv = ['scripts/localize.py', '--query', "
                    "'escape markup backslash']; runpy.run_path('scripts/localize.py', run_name='__main__')"],
                   cwd=td, env={**os.environ, "PYTHONPATH": WS, "PWD": td}, capture_output=True, text=True, timeout=120)
shutil.rmtree(td)
case("install via materialized localize", r.returncode == 0 and "EDITOR READY: python3 /tmp/swe/edit.py" in r.stdout
     and os.path.isfile("/tmp/swe/edit.py"), r.stdout + r.stderr)

NEW = '    markup = markup.replace("\\\\", "\\\\\\\\")  # $HOME `x` \'q\' """t"""\n    return markup'
BLOCK = ("<<<<<<< SEARCH\n    return markup\n=======\n" + NEW + "\n>>>>>>> REPLACE\n")

# 2. quoted heredoc: verbatim text
code, out, err = sh("python3 /tmp/swe/edit.py pkg/markup.py <<'EOF'\n" + BLOCK + "EOF")
case("quoted heredoc applies verbatim", code == 0 and NEW.encode() in read("pkg/markup.py"), out + err)
subprocess.run(["git", "-C", WS, "checkout", "-q", "--", "pkg/markup.py"])

# 3. unquoted heredoc: bash expands $HOME, backticks and backslashes; the editor recovers the raw text from /proc
code, out, err = sh("python3 /tmp/swe/edit.py pkg/markup.py <<EOF\n" + BLOCK + "EOF")
case("unquoted heredoc recovered from /proc", code == 0 and NEW.encode() in read("pkg/markup.py"),
     out + err + "\nFILE:\n" + read("pkg/markup.py").decode())
subprocess.run(["git", "-C", WS, "checkout", "-q", "--", "pkg/markup.py"])

# 4. call cut short: the terminator came out as EOF followed by a backtick (no real end line)
code, out, err = sh("python3 /tmp/swe/edit.py pkg/markup.py <<'EOF'\n" + BLOCK + "EOF`")
case("unterminated heredoc still applies, no EOF left", code == 0 and NEW.encode() in read("pkg/markup.py")
     and b"EOF" not in read("pkg/markup.py"), out + err)
code, out, err = sh("python3 /tmp/swe/edit.py pkg/markup.py 12-12 <<'EOF'\n    return 2\nEOF`")
case("range edit, unterminated", code == 0 and b"    return 2\n" in read("pkg/markup.py") and b"EOF" not in
     read("pkg/markup.py"), out + err)
subprocess.run(["git", "-C", WS, "checkout", "-q", "--", "pkg/markup.py"])

# 5. failures change nothing and exit non-zero (the harness reports status error with the message)
before = read("pkg/markup.py")
code, out, err = sh("python3 /tmp/swe/edit.py pkg/markup.py <<'EOF'\n<<<<<<< SEARCH\n    return markupp\n=======\n"
                    "    return 1\n>>>>>>> REPLACE\nEOF")
case("not found: exit 1, closest region, unchanged", code == 1 and "Closest region" in out and "     7      return markup"
     in out and read("pkg/markup.py") == before, out + err)
code, out, err = sh("python3 /tmp/swe/edit.py pkg/markup.py <<'EOF'\n<<<<<<< SEARCH\n    return markup\n=======\n"
                    "    return (markup\n>>>>>>> REPLACE\nEOF")
case("compile guard", code == 1 and "would not compile" in out and read("pkg/markup.py") == before, out + err)
code, out, err = sh("python3 /tmp/swe/edit.py tests/test_markup.py <<'EOF'\nx\nEOF")
case("tests refused", code == 1 and "test" in out, out + err)
code, out, err = sh("python3 /tmp/swe/edit.py ../../etc/passwd <<'EOF'\nx\nEOF")
case("outside workspace refused", code == 1 and "outside the workspace" in out, out + err)

# 6. new file, CRLF file, no stray files
code, out, err = sh("python3 /tmp/swe/edit.py pkg/new_mod.py <<'EOF'\nVALUE = 1\nEOF")
case("new file", code == 0 and read("pkg/new_mod.py") == b"VALUE = 1\n", out + err)
code, out, err = sh("python3 /tmp/swe/edit.py pkg/crlf.py <<'EOF'\n<<<<<<< SEARCH\nB = 2\n=======\nB = 3\nC = 4\n"
                    ">>>>>>> REPLACE\nEOF")
case("CRLF preserved", code == 0 and read("pkg/crlf.py") == b"A = 1\r\nB = 3\r\nC = 4\r\n", repr(read("pkg/crlf.py")))
status = git("status", "--porcelain")
case("only intended files changed", sorted(status.split()) == sorted(["M", "pkg/crlf.py", "??", "pkg/new_mod.py"]),
     status)

# 7. finalize reinstalls the editor on an empty patch, through the same materialization
subprocess.run(["git", "-C", WS, "checkout", "-q", "--", "."])
subprocess.run(["git", "-C", WS, "clean", "-qfd"])
shutil.rmtree("/tmp/swe", ignore_errors=True)
td = tempfile.mkdtemp(prefix="skill_")
os.makedirs(os.path.join(td, "scripts"))
for name, b64 in FILES.items():
    with open(os.path.join(td, "scripts", name), "wb") as fh:
        fh.write(base64.b64decode(b64))
r = subprocess.run([sys.executable, "-c", "import runpy, sys; sys.argv = ['scripts/finalize.py']; "
                    "runpy.run_path('scripts/finalize.py', run_name='__main__')"],
                   cwd=td, env={**os.environ, "PYTHONPATH": WS, "PWD": td}, capture_output=True, text=True, timeout=120)
case("finalize reinstalls on empty patch", "EDITOR READY" in r.stdout and os.path.isfile("/tmp/swe/edit.py"),
     r.stdout + r.stderr)

summary = {"python": sys.version.split()[0], "bash": subprocess.run(["bash", "--version"], capture_output=True,
           text=True).stdout.splitlines()[0], "passed": sum(x["ok"] for x in RESULTS), "total": len(RESULTS),
           "results": RESULTS}
with open("/kaggle/working/editor_check.json" if os.path.isdir("/kaggle/working") else "editor_check.json", "w") as fh:
    json.dump(summary, fh, indent=1)
print(json.dumps({k: summary[k] for k in ("python", "bash", "passed", "total")}))
'''


def main() -> None:
    files = {n: base64.b64encode((SCRIPTS / n).read_bytes()).decode() for n in ("localize.py", "finalize.py", "edit.py")}
    (HERE / "check.py").write_text(CHECK.replace("__FILES__", json.dumps(files)), encoding="utf-8", newline="\n")
    meta = {"id": "emanuelemiranda/g4-editor-linux-check", "title": "g4-editor-linux-check", "code_file": "check.py",
            "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": False,
            "enable_tpu": False, "enable_internet": False, "dataset_sources": [], "competition_sources": [],
            "kernel_sources": [], "model_sources": []}
    (HERE / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {HERE / 'check.py'} ({sum(len(v) for v in files.values())} b64 bytes of scripts)")


if __name__ == "__main__":
    main()
