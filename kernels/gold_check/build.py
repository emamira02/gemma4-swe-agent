"""Generate a CPU-only Kaggle kernel that verifies reference (gold) patches with the official harness, no model.

    python kernels/gold_check/build.py [--repos fastapi/fastapi psf/requests encode/httpx] [--control rich_3006]
    python -m kaggle kernels push -p kernels/gold_check

The dev panel uses Textualize/rich only because fastapi gold patches failed there ("pydantic cannot import",
2026-10-12); the hidden set is not rich-only (data/tasks.jsonl: 67 fastapi, 48 rich, 13 requests, 1 httpx). This
kernel runs the dev panel's gold phase (agent phase replaced by the reference patch, same EvalConfig, same subprocess
sandbox and wheelhouse) on every task of the given repositories and records, per task, resolved / exit code / error
and the tail of the hidden-test output, plus environment diagnostics, so the cause can be read instead of guessed.
Outputs under /kaggle/working/gold_check/: per_task.jsonl, summary.json, diag.json.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]

TEMPLATE = r'''# Auto-generated by kernels/gold_check/build.py. Do not edit by hand.
import asyncio, base64, glob, hashlib, io, json, os, subprocess, sys, time, traceback, zipfile
from pathlib import Path

T0 = time.time()
os.environ.update(LITELLM_LOCAL_MODEL_COST_MAP="True", OTEL_SDK_DISABLED="true")
WHEELHOUSE = Path("/kaggle/input/datasets/metric/gemma-4-developer-agent-wheelhouse")
tmp = Path("/tmp/wheelhouse"); tmp.mkdir(parents=True, exist_ok=True)
for w in WHEELHOUSE.glob("*.whl"):
    if "cutlass" in w.name.lower():
        continue
    name = w.name.replace("cu128", "+cu128") if ("cu128" in w.name and "+" not in w.name) else w.name
    if not (tmp / name).exists():
        os.symlink(w, tmp / name)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "--no-deps", "--force-reinstall",
                *sorted(str(w) for w in tmp.glob("*.whl"))], check=True)
import importlib; importlib.invalidate_caches()

DATA = Path("/kaggle/input/competitions/gemma-4-developer-agent")
WORK = Path("/kaggle/working"); OUT = WORK / "gold_check"; OUT.mkdir(parents=True, exist_ok=True)
AGENT = WORK / "agent"
ZIP = base64.b64decode("{zip_b64}")
assert hashlib.sha256(ZIP).hexdigest() == "{sha}"
zipfile.ZipFile(io.BytesIO(ZIP)).extractall(AGENT)
IDS = {ids}

diag = {{"python": sys.version, "executable": sys.executable,
        "data_wheels_pydantic": sorted(os.path.basename(p) for p in glob.glob(str(DATA / "wheels" / "**" / "*pydantic*"), recursive=True))[:40],
        "data_wheels_top": sorted(os.listdir(DATA / "wheels"))[:60] if (DATA / "wheels").exists() else None}}
for mod in ("pydantic", "pydantic_core", "fastapi", "starlette"):
    r = subprocess.run([sys.executable, "-c", f"import {{mod}}, sys; print({{mod}}.__file__, getattr({{mod}}, '__version__', ''))"],
                       capture_output=True, text=True)
    diag[f"kernel_import_{{mod}}"] = (r.stdout + r.stderr)[-600:]
(OUT / "diag.json").write_text(json.dumps(diag, indent=1))
print(json.dumps(diag, indent=1), flush=True)

import yaml
from adk_submission.registry import ModelRegistry
from swegemma.config import EvalConfig, build_submission_limits
from swegemma.evaluate import Evaluator
from swegemma.models import load_tasks

ev = (yaml.safe_load((AGENT / "eval_config.yaml").read_text()) or {{}}).get("evaluation", {{}})
limits, gen = build_submission_limits()
cfg = EvalConfig(tasks_path=DATA / "tasks.jsonl", snapshots_dir=DATA / "snapshots", results_dir=OUT / "gold",
                 submission_dir=AGENT, models=ModelRegistry(), sandbox="subprocess",
                 timeout_seconds=int(ev.get("timeout_seconds", 300)), max_time_minutes=float(ev.get("max_time_minutes", 60)),
                 max_tool_calls=int(ev.get("max_tool_calls", 100)), max_turns=ev.get("max_turns"),
                 limits=limits, generation_constraints=gen,
                 graph_dir=str(DATA / "graphs"), embeddings_dir=str(DATA / "embeddings"),
                 wheels_dir=DATA / "wheels", verbose=False)
tasks = {{t.instance_id: t for t in load_tasks(DATA / "tasks.jsonl")}}
todo = [tasks[i] for i in IDS if i in tasks]
gold_ev = Evaluator(cfg)
async def _gold_phase1(task, *a, **k):
    from adk_eval_core import SessionTrace
    return task.patch, None, SessionTrace()
gold_ev._run_agent_sandbox = _gold_phase1

rows = []
with open(OUT / "per_task.jsonl", "w") as fh:
    for i, t in enumerate(todo, 1):
        t1 = time.time()
        row = {{"id": t.instance_id, "repo": t.repo}}
        try:
            r = asyncio.run(gold_ev.evaluate_task(task=t, task_index=i, total_tasks=len(todo)))
            row.update(resolved=bool(r.resolved), exit=r.test_exit_code, error=(r.error or "")[:600],
                       test_output_tail=(getattr(r, "test_output", "") or "")[-2500:])
        except Exception as e:
            row.update(resolved=False, error=f"{{type(e).__name__}}: {{e}}"[:600], test_output_tail=traceback.format_exc()[-2500:])
        row["duration_s"] = round(time.time() - t1, 1)
        rows.append(row); fh.write(json.dumps(row) + "\n"); fh.flush()
        print(f"[{{i}}/{{len(todo)}}] {{t.instance_id}} {{t.repo}} resolved={{row['resolved']}} exit={{row.get('exit')}} "
              f"t={{row['duration_s']}}s {{row['error'][:120]}}", flush=True)

by_repo = {{}}
for r in rows:
    d = by_repo.setdefault(r["repo"], {{"n": 0, "resolved": 0}})
    d["n"] += 1; d["resolved"] += r["resolved"]
summary = {{"n": len(rows), "resolved": sum(r["resolved"] for r in rows), "by_repo": by_repo, "wall_s": round(time.time() - T0)}}
(OUT / "summary.json").write_text(json.dumps(summary, indent=1))
print(json.dumps(summary, indent=1))
'''


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repos", nargs="+", default=["fastapi/fastapi", "psf/requests", "encode/httpx"])
    ap.add_argument("--control", nargs="*", default=["rich_3006", "rich_3067"], help="rich tasks known to pass")
    ap.add_argument("--zip", type=Path, default=ROOT / "build" / "baselines" / "B1.zip",
                    help="any valid bundle: the gold phase never runs the agent, the harness only needs a submission dir")
    ap.add_argument("--kernel-id", default="emanuelemiranda/g4-gold-check")
    a = ap.parse_args()
    data = a.zip.read_bytes()
    tasks = [json.loads(l) for l in (ROOT / "data" / "tasks.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
    ids = sorted(t["instance_id"] for t in tasks if t["repo"] in a.repos) + list(a.control)
    src = TEMPLATE.format(zip_b64=base64.b64encode(data).decode(), sha=hashlib.sha256(data).hexdigest(), ids=json.dumps(ids))
    compile(src, "gold_check.py", "exec")
    (HERE / "gold_check.py").write_text(src, encoding="utf-8", newline="\n")
    panel_meta = json.loads((HERE.parent / "agent_eval" / "kernel-metadata.json").read_text(encoding="utf-8"))
    meta = {"id": a.kernel_id, "title": "g4-gold-check", "code_file": "gold_check.py", "language": "python",
            "kernel_type": "script", "is_private": True, "enable_gpu": False, "enable_tpu": False,
            "enable_internet": False, "dataset_sources": ["metric/gemma-4-developer-agent-wheelhouse"],
            "competition_sources": ["gemma-4-developer-agent"], "kernel_sources": [], "model_sources": [],
            "docker_image": panel_meta["docker_image"]}
    (HERE / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"gold check: {len(ids)} tasks ({', '.join(a.repos)} + control {a.control}) -> {HERE / 'gold_check.py'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
