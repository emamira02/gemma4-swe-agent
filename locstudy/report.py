"""Render paper-ready tables (Markdown) and figures (PNG) from summary.json — numbers are never typed by hand."""
from __future__ import annotations

import json
from pathlib import Path

LABEL = {"ident": "Identifiers", "ident+": "Identifiers+", "bm25": "BM25", "emb": "Embedding nbrs",
         "graph": "Graph 1-hop", "graph2": "Graph 2-hop", "rrf": "RRF", "rrf+": "RRF+"}


def _fmt(ci: list[float]) -> str:
    """Percent with one decimal from 4-dp stored values (single rounding step)."""
    return f"{100 * ci[0]:.1f} [{100 * ci[1]:.1f}, {100 * ci[2]:.1f}]"


def table(block: dict, cols: tuple[str, ...]) -> str:
    head = "| Signal | " + " | ".join(cols) + " |\n|---|" + "---|" * len(cols) + "\n"
    rows = []
    for s, lab in LABEL.items():
        if s in block:
            rows.append(f"| {lab} | " + " | ".join(_fmt(block[s][c]) if isinstance(block[s][c], list) else str(block[s][c])
                                                  for c in cols) + " |")
    return head + "\n".join(rows)


def render(summary: dict, sens: dict | None, out_md: Path) -> None:
    c, prov = summary["coverage"], summary["provenance"]
    lines = [
        "<!-- AUTO-GENERATED by `python -m locstudy report`. Do not edit numbers by hand. -->",
        f"# Results (schema v{prov['schema_version']}, commit {str(prov['git_commit'])[:8]}{' +dirty' if prov['git_dirty'] else ''}, {prov['utc']})",
        "",
        f"Tasks {c['tasks']} · source-changing {c['source_change']} · with gold symbols {c['with_gold_symbol']} · "
        f"hunks mapped {c['hunks_mapped']}/{c['hunks_total']} · label/@@-header agreement "
        f"{c['label_header_agreement'][0]}/{c['label_header_agreement'][1]} ({c['label_header_agreement'][2]}; weak proxy, see audit) · "
        f"edit hunks with all removed lines inside the gold symbol {c['label_full_coverage'][0]}/{c['label_full_coverage'][1]} · "
        f"issues naming a resolvable symbol {c['issue_names_resolvable_symbol']}/{c['source_change']}.",
        f"Task types (heuristic): {c['by_type']}. Repositories: {c['by_repo']}.",
        "",
        "Values: % mean [95% bootstrap CI], task-level resampling, "
        f"{prov['params']['n_boot']} resamples, seed {prov['params']['seed']}.",
        "",
        f"## Table 1 — Symbol level (n={summary['symbol_level']['n']})",
        table(summary["symbol_level"], ("R@1", "R@5", "R@20", "R@50", "MRR")),
        "",
        "## Table 2 — Reading budget (symbol level): hit within N tokens of reading, and median tokens to first hit",
        table(summary["symbol_level"], ("Hit@2k_tok", "Hit@8k_tok", "Hit@32k_tok", "median_tokens_to_hit")),
        "",
        f"## Table 3 — File level (n={summary['file_level']['n']})",
        table(summary["file_level"], ("R@1", "R@5", "R@20", "MRR")),
        "",
        f"## Table 4a — Issues that name a resolvable symbol (n={summary['by_anchor']['named_symbol']['n']})",
        table(summary["by_anchor"]["named_symbol"], ("R@5", "R@20", "R@50", "MRR")),
        "",
        f"## Table 4b — Issues that name none (n={summary['by_anchor']['no_named_symbol']['n']})",
        table(summary["by_anchor"]["no_named_symbol"], ("R@5", "R@20", "R@50", "MRR")),
        "",
        "## Table 5 — Paired comparisons, RRF+ vs each signal (symbol level)",
    ]
    for name, res in summary["comparisons"].items():
        lines += [f"**{name}**", "", "| Other | Δ (RRF+ − other) [95% CI] | RRF+ only | other only | McNemar p | Holm p |",
                  "|---|---|---|---|---|---|"]
        for s, r in res.items():
            lines.append(f"| {LABEL[s]} | {r['diff']:+.3f} [{r['ci'][0]:+.3f}, {r['ci'][1]:+.3f}] | {r['primary_only']} | "
                         f"{r['other_only']} | {r['mcnemar_p']:.4f} | {r['mcnemar_p_holm']:.4f} |")
        lines.append("")
    lines += ["## Hop distance from nearest anchor to the edited symbol (call graph, undirected)",
              ", ".join(f"{k}: {v}" for k, v in summary["hop_distance"].items()), ""]
    lines += ["## Per repository (symbol level, R@5 / R@20)"]
    for repo, blk in summary["by_repo"].items():
        if blk.get("n"):
            lines.append(f"- {repo} (n={blk['n']}): BM25 {_fmt(blk['bm25']['R@5'])} / {_fmt(blk['bm25']['R@20'])} · "
                         f"RRF+ {_fmt(blk['rrf+']['R@5'])} / {_fmt(blk['rrf+']['R@20'])}")
    lines.append("")
    if sens:
        lines += ["## Sensitivity (one-at-a-time; point estimates)", "| Setting | BM25 R@5 | RRF R@5 | RRF+ R@5 | RRF+ R@20 | RRF+ MRR |",
                  "|---|---|---|---|---|---|"]
        for k, v in sens.items():
            lines.append(f"| {k} | {v['bm25']['R@5']:.3f} | {v['rrf']['R@5']:.3f} | {v['rrf+']['R@5']:.3f} | "
                         f"{v['rrf+']['R@20']:.3f} | {v['rrf+']['MRR']:.3f} |")
    out_md.write_text("\n".join(lines) + "\n", encoding="utf-8")


def figures(summary: dict, out_dir: Path) -> list[Path]:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    out_dir.mkdir(parents=True, exist_ok=True)
    ks = (1, 5, 10, 20, 50)
    paths = []
    style = {"bm25": ("#1f6feb", "-"), "graph": ("#8250df", "--"), "emb": ("#57606a", ":"), "rrf+": ("#d1242f", "-")}

    fig, axes = plt.subplots(1, 2, figsize=(11, 4), sharey=True)
    for ax, (title, blk) in zip(axes, (("Issue names a symbol", summary["by_anchor"]["named_symbol"]),
                                       ("Issue names none", summary["by_anchor"]["no_named_symbol"]))):
        for s, (col, ls) in style.items():
            m = [blk[s][f"R@{k}"][0] for k in ks]
            lo = [blk[s][f"R@{k}"][1] for k in ks]
            hi = [blk[s][f"R@{k}"][2] for k in ks]
            ax.plot(ks, m, ls, color=col, marker="o", label=LABEL[s])
            ax.fill_between(ks, lo, hi, color=col, alpha=0.12)
        ax.set_xscale("log"); ax.set_xticks(ks); ax.set_xticklabels(ks)
        ax.set_title(f"{title} (n={blk['n']})"); ax.set_xlabel("k (symbols ranked)"); ax.grid(alpha=0.3)
    axes[0].set_ylabel("Recall@k of an edited symbol"); axes[0].legend(frameon=False)
    fig.tight_layout(); p = out_dir / "fig1_recall_by_anchor.png"; fig.savefig(p, dpi=200); plt.close(fig); paths.append(p)

    fig, ax = plt.subplots(figsize=(6, 3.6))
    hop = summary["hop_distance"]
    labels = [k if k != "None" else ">4 / unreachable" for k in hop]
    ax.bar(labels, list(hop.values()), color="#8250df")
    ax.set_xlabel("Call-graph hops from nearest anchor to edited symbol"); ax.set_ylabel("Tasks"); ax.grid(axis="y", alpha=0.3)
    fig.tight_layout(); p = out_dir / "fig2_hop_distance.png"; fig.savefig(p, dpi=200); plt.close(fig); paths.append(p)

    fig, ax = plt.subplots(figsize=(6, 3.6))
    budgets = ("Hit@2k_tok", "Hit@8k_tok", "Hit@32k_tok")
    x = range(len(budgets))
    for i, (s, (col, _)) in enumerate(style.items()):
        vals = [summary["symbol_level"][s][b][0] for b in budgets]
        ax.bar([xi + i * 0.2 - 0.3 for xi in x], vals, width=0.2, color=col, label=LABEL[s])
    ax.set_xticks(list(x)); ax.set_xticklabels(["2k", "8k", "32k"]); ax.set_xlabel("Tokens of source read (≈ chars/4)")
    ax.set_ylabel("Edited symbol reached"); ax.legend(frameon=False, fontsize=8); ax.grid(axis="y", alpha=0.3)
    fig.tight_layout(); p = out_dir / "fig3_reading_budget.png"; fig.savefig(p, dpi=200); plt.close(fig); paths.append(p)
    return paths


def render_llm(llm: dict, out_md: Path) -> None:
    lab = {**LABEL, "hyp": "Model symbol hypotheses", "hyp_fused": "Hypotheses + fusion", "rerank50": "Model re-rank of BM25 top-50",
           "policy": "Two-mode policy"}
    m = llm["meta"]
    lines = ["<!-- AUTO-GENERATED by `python -m locstudy llm`. -->", "# Model-in-the-loop results",
             f"Prompt sha {m.get('prompt_sha')} · tasks {m.get('n_ok')}/{m.get('n_tasks')} · hypothesis JSON parsed "
             f"{m.get('hyp_parse_rate')} · re-rank JSON parsed {m.get('rerank_parse_rate')} · hypotheses resolved "
             f"{m.get('hyp_resolved_rate')} · mean model latency/task {m.get('mean_latency_s')} s · tokens {m.get('tokens')}", ""]
    for key, title in (("all", "All tasks"), ("named_symbol", "Issue names a symbol"), ("no_named_symbol", "Issue names none")):
        blk = llm[key]
        lines += [f"## {title} (n={blk['n']})", "| Signal | R@1 | R@5 | R@20 | MRR | Hit@8k_tok |", "|---|---|---|---|---|---|"]
        for s in ("bm25", "rrf+", "hyp", "hyp_fused", "rerank50", "policy"):
            if s in blk:
                lines.append(f"| {lab[s]} | " + " | ".join(_fmt(blk[s][c]) for c in ("R@1", "R@5", "R@20", "MRR", "Hit@8k_tok")) + " |")
        lines.append("")
    lines.append("## Pre-specified paired tests")
    for name, res in llm["tests"].items():
        for s, r in res.items():
            lines.append(f"- {name}: {name.split('_')[0]} primary vs {s}: Δ {r['diff']:+.3f} [{r['ci'][0]:+.3f}, {r['ci'][1]:+.3f}], "
                         f"McNemar p {r['mcnemar_p']:.4f}, Holm p {r['mcnemar_p_holm']:.4f} (n={r['n']})")
    out_md.write_text(chr(10).join(lines) + chr(10), encoding="utf-8")


_SLOT = __import__("re").compile(r"\{\{([^}|]+)(?:\|(\w+))?\}\}")


def _lookup(doc, path: str):
    cur = doc
    for part in path.strip().split("/"):
        part = part.replace("~", "/")  # "~" escapes "/" inside keys, e.g. by_repo/Textualize~rich
        cur = cur[int(part)] if isinstance(cur, list) else cur[part]
    return cur


_BLOCK = __import__("re").compile(r"<!-- if:(\w+) -->(.*?)<!-- endif -->", __import__("re").S)


def fill_template(template: str, docs: dict[str, dict]) -> str:
    """Replace {{source:path/to/value|fmt}} with values from result files. Unknown paths raise (no silent gaps).
    <!-- if:src --> ... <!-- endif --> blocks are kept only when result source `src` exists.
    fmt: pct (x100, 1 dp, %), ci (mean [lo, hi] as %), f2, f3, int, raw."""
    template = _BLOCK.sub(lambda m: m.group(2) if docs.get(m.group(1)) else "", template)
    def sub(m):
        ref, fmt = m.group(1), (m.group(2) or "raw")
        src, _, path = ref.partition(":")
        v = _lookup(docs[src], path)
        if fmt == "pct":
            return f"{100 * v:.1f}%"
        if fmt == "ci":
            return f"{100 * v[0]:.1f}% [{100 * v[1]:.1f}, {100 * v[2]:.1f}]"
        if fmt == "f2":
            return f"{v:.2f}"
        if fmt == "f3":
            return f"{v:.3f}"
        if fmt == "int":
            return f"{int(v):,}"
        return str(v)
    return _SLOT.sub(sub, template)


def build(results_dir: Path, paper_dir: Path) -> None:
    summary = json.loads((results_dir / "summary.json").read_text(encoding="utf-8"))
    sp = results_dir / "sensitivity.json"
    sens = json.loads(sp.read_text(encoding="utf-8")) if sp.exists() else None
    render(summary, sens, paper_dir / "RESULTS.md")
    figures(summary, paper_dir / "figures")
    tpl = paper_dir / "PAPER.template.md"
    if tpl.exists():
        docs = {"s": summary, "sens": sens or {}}
        llm = results_dir / "llm_summary.json"
        if llm.exists():
            docs["llm"] = json.loads(llm.read_text(encoding="utf-8"))
            render_llm(docs["llm"], paper_dir / "RESULTS_LLM.md")
        audit = results_dir / "label_audit.json"
        if audit.exists():
            docs["audit"] = json.loads(audit.read_text(encoding="utf-8"))
        text = fill_template(tpl.read_text(encoding="utf-8"), docs)
        (paper_dir / "PAPER.md").write_text("<!-- AUTO-GENERATED from PAPER.template.md + results/*.json -->\n" + text,
                                            encoding="utf-8")
