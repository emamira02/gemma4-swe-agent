LABEL = {"ident": "Identifiers", "ident+": "Identifiers+", "bm25": "BM25", "emb": "Embedding nbrs",
         "graph": "Graph 1-hop", "graph2": "Graph 2-hop", "rrf": "RRF", "rrf+": "RRF+", "lex": "Lexical policy (no graph)"}


def _fmt(ci: list[float]) -> str:
    """Percent with one decimal from 4-dp stored values (single rounding step)."""
    return f"{100 * ci[0]:.1f} [{100 * ci[1]:.1f}, {100 * ci[2]:.1f}]"


def table(block: dict, cols: tuple[str, ...]) -> str:
    head = "| Signal | " + " | ".join(cols) + " |\n|---|" + "---|" * len(cols) + "\n"
    rows = []
    for s, lab in LABEL.items():
        if s in block:
            rows.append(f"| {lab} | " + " | ".join(_fmt(block[s][c]) if isinstance(block[s][c], list) else str(block[s][c])
                                                  for c in cols) + " |")
    return head + "\n".join(rows)


def render(summary: dict, sens: dict | None, out_md: Path) -> None:
    c, prov = summary["coverage"], summary["provenance"]
    lines = [
        "<!-- AUTO-GENERATED by `python -m locstudy report`. Do not edit numbers by hand. -->",
        f"# Results (schema v{prov['schema_version']}, commit {str(prov['git_commit'])[:8]}{' +dirty' if prov['git_dirty'] else ''}, {prov['utc']})",
        "",
        f"Tasks {c['tasks']} · source-changing {c['source_change']} · with gold symbols {c['with_gold_symbol']} · "
        f"hunks mapped {c['hunks_mapped']}/{c['hunks_total']} · label/@@-header agreement "
        f"{c['label_header_agreement'][0]}/{c['label_header_agreement'][1]} ({c['label_header_agreement'][2]}; weak proxy, see audit) · "
        f"edit hunks with all removed lines inside the gold symbol {c['label_full_coverage'][0]}/{c['label_full_coverage'][1]} · "
        f"issues naming a resolvable symbol {c['issue_names_resolvable_symbol']}/{c['source_change']}.",
        f"Task types (heuristic): {c['by_type']}. Repositories: {c['by_repo']}.",
        "",
        "Values: % mean [95% bootstrap CI], task-level resampling, "
        f"{prov['params']['n_boot']} resamples, seed {prov['params']['seed']}.",
        "",
        f"## Table 1 — Symbol level (n={summary['symbol_level']['n']})",
        table(summary["symbol_level"], ("R@1", "R@5", "R@20", "R@50", "MRR")),
        "",
        "## Table 2 — Reading budget (symbol level): hit within N tokens of reading, and median tokens to first hit",
        table(summary["symbol_level"], ("Hit@2k_tok", "Hit@8k_tok", "Hit@32k_tok", "median_tokens_to_hit")),
        "",
        f"## Table 3 — File level (n={summary['file_level']['n']})",
        table(summary["file_level"], ("R@1", "R@5", "R@20", "MRR")),
        "",
        f"## Table 4a — Issues that name a resolvable symbol (n={summary['by_anchor']['named_symbol']['n']})",
        table(summary["by_anchor"]["named_symbol"], ("R@5", "R@20", "R@50", "MRR")),
        "",
        f"## Table 4b — Issues that name none (n={summary['by_anchor']['no_named_symbol']['n']})",
        table(summary["by_anchor"]["no_named_symbol"], ("R@5", "R@20", "R@50", "MRR")),
        "",
        "## Table 5 — Paired comparisons, RRF+ vs each signal (symbol level)",
    ]
    for name, res in summary["comparisons"].items():
        lines += [f"**{name}**", "", "| Other | Δ (RRF+ − other) [95% CI] | RRF+ only | other only | McNemar p | Holm p |",
                  "|---|---|---|---|---|---|"]
        for s, r in res.items():
            lines.append(f"| {LABEL[s]} | {r['diff']:+.3f} [{r['ci'][0]:+.3f}, {r['ci'][1]:+.3f}] | {r['primary_only']} | "
                         f"{r['other_only']} | {r['mcnemar_p']:.4f} | {r['mcnemar_p_holm']:.4f} |")
        lines.append("")
    lines += ["## Hop distance from nearest anchor to the edited symbol (call graph, undirected)",
              ", ".join(f"{k}: {v}" for k, v in summary["hop_distance"].items()), ""]
    lines += ["## Per repository (symbol level, R@5 / R@20)"]
    for repo, blk in summary["by_repo"].items():
        if blk.get("n"):
            lines.append(f"- {repo} (n={blk['n']}): BM25 {_fmt(blk['bm25']['R@5'])} / {_fmt(blk['bm25']['R@20'])} · "
                         f"RRF+ {_fmt(blk['rrf+']['R@5'])} / {_fmt(blk['rrf+']['R@20'])}")
    lines.append("")
    if sens:
        lines += ["## Sensitivity (one-at-a-time; point estimates)", "| Setting | BM25 R@5 | RRF R@5 | RRF+ R@5 | RRF+ R@20 | RRF+ MRR |",
                  "|---|---|---|---|---|---|"]
        for k, v in sens.items():
            lines.append(f"| {k} | {v['bm25']['R@5']:.3f} | {v['rrf']['R@5']:.3f} | {v['rrf+']['R@5']:.3f} | "
                         f"{v['rrf+']['R@20']:.3f} | {v['rrf+']['MRR']:.3f} |")
    out_md.write_text("\n".join(lines) + "\n", encoding="utf-8")


